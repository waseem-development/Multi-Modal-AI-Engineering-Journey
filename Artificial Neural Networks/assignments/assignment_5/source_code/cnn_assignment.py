# CNNs with Keras: MNIST, CIFAR-10, Fashion-MNIST, CIFAR-100

## Importing Libraries
"""

import numpy as np
import tensorflow as tf

from tensorflow.keras.datasets import mnist, cifar10, fashion_mnist, cifar100
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Input, Conv2D, MaxPooling2D, Dropout, Flatten, Dense
from tensorflow.keras.utils import to_categorical
from tensorflow.keras.optimizers import SGD

"""# 1. MNIST

## Load and prepare the dataset
"""

(X_train, y_train), (X_test, y_test) = mnist.load_data()

# scale to 0-1 and add channel dimension
X_train = X_train.astype("float32").reshape(60000, 28, 28, 1) / 255
X_test = X_test.astype("float32").reshape(10000, 28, 28, 1) / 255

# one-hot encode labels
y_train = to_categorical(y_train, 10)
y_test = to_categorical(y_test, 10)

print(X_train.shape, y_train.shape)

"""## Define the model"""

model = Sequential()
model.add(Input(shape=(28, 28, 1)))
model.add(Conv2D(32, (3, 3), activation="relu"))
model.add(MaxPooling2D((2, 2)))
model.add(Conv2D(64, (3, 3), activation="relu"))
model.add(MaxPooling2D((2, 2)))
model.add(Flatten())
model.add(Dropout(0.5))
model.add(Dense(10, activation="softmax"))

model.summary()

"""## Compile and train the model"""

model.compile(loss="categorical_crossentropy", optimizer=SGD(learning_rate=0.01), metrics=["accuracy"])

history = model.fit(X_train, y_train, batch_size=128, epochs=10, validation_split=0.1)

"""## Evaluate and predict the model"""

score = model.evaluate(X_test, y_test, verbose=0)
print("Test loss:", score[0])
print("Test accuracy:", score[1])

# predict first 10 test images
pred = np.argmax(model.predict(X_test[:10], verbose=0), axis=1)
print("Predicted:", pred)
print("Actual:   ", np.argmax(y_test[:10], axis=1))

"""# 2. CIFAR-10

## Load and prepare the dataset
"""

(X_train, y_train), (X_test, y_test) = cifar10.load_data()

class_names = ['airplane', 'automobile', 'bird', 'cat', 'deer',
               'dog', 'frog', 'horse', 'ship', 'truck']

y_train = y_train.flatten()
y_test = y_test.flatten()

# scale to 0-1
X_train = X_train.astype("float32") / 255.0
X_test = X_test.astype("float32") / 255.0

print(X_train.shape, y_train.shape)

"""## Define the model"""

model = Sequential()
model.add(Input(shape=(32, 32, 3)))
model.add(Conv2D(32, (3, 3), activation="relu"))
model.add(MaxPooling2D((2, 2)))
model.add(Conv2D(64, (3, 3), activation="relu"))
model.add(MaxPooling2D((2, 2)))
model.add(Conv2D(64, (3, 3), activation="relu"))
model.add(Flatten())
model.add(Dense(64, activation="relu"))
model.add(Dense(10, activation="softmax"))

model.summary()

"""## Compile and train the model"""

model.compile(optimizer=SGD(learning_rate=0.01), loss="sparse_categorical_crossentropy", metrics=["accuracy"])

history = model.fit(X_train, y_train, batch_size=64, epochs=10, validation_data=(X_test, y_test))

"""## Evaluate and predict the model"""

score = model.evaluate(X_test, y_test, verbose=0)
print("Test loss:", score[0])
print("Test accuracy:", score[1])

# predict first 10 test images
pred = np.argmax(model.predict(X_test[:10], verbose=0), axis=1)
for i in range(10):
    print("Predicted:", class_names[pred[i]], "| Actual:", class_names[y_test[i]])

